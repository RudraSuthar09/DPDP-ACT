-- Submissions export: a spreadsheet of a consent form's submissions, and an
-- optional authorized folder to put it in.
--
-- WHAT THIS PLATFORM CAN HONESTLY EXPORT, and why there are two exports.
--
-- Central Postgres holds, per submission: when it arrived, through which
-- channel, the per-purpose consent answers, the delivery outcome, and
-- subject_ref (a per-tenant HMAC, not a readable identity). It has NEVER held
-- a submitted FIELD VALUE — not a text value, not a file — and this migration
-- does not change that. So a spreadsheet generated centrally cannot contain
-- field values, and the honest thing is to say so in the sheet rather than
-- ship an export with silently empty columns.
--
-- Hence:
--   * the DASHBOARD export (always available, generated by this backend) =
--     timestamps, the customer's display name where one was configured, the
--     consent answers, per-file METADATA, and delivery status. Every text
--     value is marked as held on the client's own Gateway.
--   * the GATEWAY export (when a destination is configured) = the same
--     columns PLUS every field value, built by the tenant's own Gateway in
--     the authorized folder, because that is the only place the values exist.
--
-- THE ONE NEW RECORD: consent_form_submission_files, metadata about each file
-- an upload field produced. It exists because the delivery payload is nulled
-- on acknowledgement (1737005000000) — by design — so without it the system
-- forgets a file was ever collected the moment it is safely delivered, and
-- could not list it in an export, nor tell an auditor it existed.
--
-- It is METADATA, not content: a label, the filename the SERVER generated, a
-- byte count, the content type proved from the bytes, and which destination
-- it was written to. No bytes, no path on the customer's disk, no respondent
-- text. Same category as storage_roots.name or data_principals.display_name
-- (1737004900000) — the platform recording what it arranged, not what it was
-- given. I1 is untouched.

-- Up Migration

-- --------------------------------------------------------------------------
-- 1. Per-file metadata
-- --------------------------------------------------------------------------

CREATE TABLE consent_form_submission_files (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id      uuid NOT NULL DEFAULT app.current_tenant()
                   REFERENCES organisations (id),

  submission_id  uuid NOT NULL REFERENCES consent_form_submissions (id),
  form_id        uuid NOT NULL REFERENCES consent_forms (id),
  -- The upload field this file came from. Deliberately NOT a foreign key into
  -- consent_form_customer_fields: a field may later be removed, and an export
  -- must still be able to say that this file was collected. The label below
  -- is captured at submit time for the same reason.
  field_id       uuid NOT NULL,
  field_label    text NOT NULL,

  -- The filename the SERVER generated (enterpriseCopyFilename) — never the
  -- respondent's own, which is untrusted input and never reaches this table.
  filename       text NOT NULL,
  byte_size      integer NOT NULL CHECK (byte_size > 0),
  -- Proved from the file's leading bytes (shared/src/consent-uploads.ts:
  -- inspectUpload), never the Content-Type the client claimed.
  content_type   text NOT NULL,

  -- Which authorized location this file was written into, or NULL for the
  -- Central DPDP Storage write. Not secret: the same kind of reference
  -- storage_mappings and consent_form_submission_deliveries already hold in
  -- clear.
  storage_root_id uuid REFERENCES storage_roots (id),

  created_at     timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE consent_form_submission_files IS
  'METADATA about each file an upload field collected: label, server-generated '
  'filename, size, proved content type, destination. NO bytes, no customer '
  'path, no respondent text — the file itself lives only in the folder the '
  'tenant''s Gateway wrote it to. Exists because the delivery payload is '
  'nulled on acknowledgement, so this is the only durable record that a file '
  'was collected at all.';

SELECT app.apply_tenant_rls('public.consent_form_submission_files');

CREATE INDEX consent_form_submission_files_form_idx
  ON consent_form_submission_files (tenant_id, form_id, created_at DESC);
CREATE INDEX consent_form_submission_files_submission_idx
  ON consent_form_submission_files (tenant_id, submission_id);

-- One row per (submission, field): a resubmission of the same field within
-- one submission would be a bug, and a duplicate row would double-count a
-- file in the export.
CREATE UNIQUE INDEX consent_form_submission_files_one_per_field
  ON consent_form_submission_files (submission_id, field_id);

-- A plain FK does not apply RLS during its referential-integrity check — the
-- same Postgres behaviour 1737005400000 guards against for
-- target_storage_root_id. Without this a request could bind a file record to
-- ANOTHER tenant's storage root: the FK would accept the id, because its
-- integrity check does not run under the tenant policy. Refused at the
-- database, not only in whatever service writes the row.
--
-- Written exactly like 1737005400000's check: an ordinary invoker-rights
-- function, so it runs as the calling role inside the caller's tenant
-- context. It needs no elevated rights — the storage_roots rows it must see
-- are precisely this tenant's — and so no SECURITY DEFINER and no search_path
-- pin (that pairing is for the pre-tenant lookups, which have no tenant to
-- run as).
--
-- storage_root_id is currently always written NULL (the destination is
-- resolved later, inside the delivery module), so today this guards a path no
-- caller uses. It is here so the column cannot become a cross-tenant hole the
-- day something starts filling it.
CREATE OR REPLACE FUNCTION app.check_submission_file_root_tenant() RETURNS trigger
  LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.storage_root_id IS NOT NULL THEN
    IF NOT EXISTS (
      SELECT 1 FROM storage_roots
       WHERE id = NEW.storage_root_id AND tenant_id = NEW.tenant_id
    ) THEN
      RAISE EXCEPTION 'storage_root_id does not belong to this tenant';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER consent_form_submission_files_check_root_tenant
  BEFORE INSERT OR UPDATE OF storage_root_id ON consent_form_submission_files
  FOR EACH ROW EXECUTE FUNCTION app.check_submission_file_root_tenant();

-- --------------------------------------------------------------------------
-- 2. The form's optional spreadsheet destination
-- --------------------------------------------------------------------------

ALTER TABLE consent_forms ADD COLUMN export_storage_root_id uuid REFERENCES storage_roots (id);

COMMENT ON COLUMN consent_forms.export_storage_root_id IS
  'Optional: the authorized WRITABLE storage location (a storage_roots row) '
  'this form''s submissions spreadsheet can be saved into. NULL = dashboard '
  'download only. The customer picks it by NAME from a dropdown of their '
  'connected writable locations on the form''s Submissions panel — no id or '
  'path is ever shown or typed. It is a whole location, not a subfolder: the '
  'spreadsheet is written at the top of it. The application only offers, and '
  'only accepts, an active gateway-provider root, which exists only because '
  'an administrator granted WRITE on that folder; a read-only grant is a '
  'data_sources record and cannot be chosen here. The application re-checks '
  'this each time it is set; the database enforces only that the root '
  'belongs to the same tenant as the form.';

-- Same RLS-at-FK-time hole as above, closed the same way: an ordinary
-- invoker-rights check written like 1737005400000's, fired only when the
-- column is actually written — not on every update of a form.
CREATE OR REPLACE FUNCTION app.check_form_export_root_tenant() RETURNS trigger
  LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.export_storage_root_id IS NOT NULL THEN
    IF NOT EXISTS (
      SELECT 1 FROM storage_roots
       WHERE id = NEW.export_storage_root_id AND tenant_id = NEW.tenant_id
    ) THEN
      RAISE EXCEPTION 'export_storage_root_id does not belong to this tenant';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER consent_forms_check_export_root_tenant
  BEFORE INSERT OR UPDATE OF export_storage_root_id ON consent_forms
  FOR EACH ROW EXECUTE FUNCTION app.check_form_export_root_tenant();

-- Down Migration

-- Reverse order of creation. IF EXISTS throughout, like 1737005400000's down,
-- so a partially-applied or hand-repaired schema still rolls back cleanly.
-- Destructive by nature: dropping consent_form_submission_files discards the
-- file METADATA recorded since this migration (never the files themselves,
-- which live only in the client's own folders), and dropping the column
-- forgets each form's chosen spreadsheet folder.
DROP TRIGGER IF EXISTS consent_forms_check_export_root_tenant ON consent_forms;
DROP FUNCTION IF EXISTS app.check_form_export_root_tenant();
ALTER TABLE consent_forms DROP COLUMN IF EXISTS export_storage_root_id;

DROP TRIGGER IF EXISTS consent_form_submission_files_check_root_tenant ON consent_form_submission_files;
DROP FUNCTION IF EXISTS app.check_submission_file_root_tenant();
DROP TABLE IF EXISTS consent_form_submission_files;
